interface LanguageContextValue {
  locale: Locale
  dateLocale: string
  setLocale: (locale: Locale) => void
  t: (key: string, values?: TranslationValues) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('vi')

  useEffect(() => {
    const timeoutId = window.setTimeout(() => {
      const savedLocale = window.localStorage.getItem('chatly-locale')
      if (savedLocale === 'vi' || savedLocale === 'en') {
        setLocaleState(savedLocale)
      }
    }, 0)
    return () => window.clearTimeout(timeoutId)
  }, [])

  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale)
    window.localStorage.setItem('chatly-locale', nextLocale)
    document.documentElement.lang = nextLocale
  }, [])

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<LanguageContextValue>(
    () => ({
      locale,
      dateLocale: locale === 'vi' ? 'vi-VN' : 'en-US',
      setLocale,
      t: (key, values) => {
        let translated = translations[locale][key] ?? translations.en[key] ?? key
        Object.entries(values ?? {}).forEach(([name, replacement]) => {
          translated = translated.replaceAll(`{${name}}`, String(replacement))
        })
        return translated
      },
    }),
    [locale, setLocale]
  )

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useI18n() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useI18n must be used within LanguageProvider')
  return context
}
