import { spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmdirSync,
  writeFileSync,
} from 'node:fs'
import { dirname, extname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const generatedPath = join(projectRoot, 'src', 'app', 'tailwind-sources.generated.css')
const supportedExtensions = new Set(['.js', '.jsx', '.mdx', '.ts', '.tsx'])

function ensureWindowsWasmBinding() {
  if (process.platform !== 'win32') return

  process.env.NAPI_RS_FORCE_WASI = '1'
  const scopeDirectory = join(projectRoot, 'node_modules', '@tailwindcss')
  const destination = join(scopeDirectory, 'oxide-wasm32-wasi')
  if (existsSync(join(destination, 'package.json'))) return

  const archive = join(projectRoot, 'scripts', 'vendor', 'tailwindcss-oxide-wasm32-wasi-4.2.3.tgz')
  if (!existsSync(archive)) throw new Error(`Missing Tailwind WASM archive: ${archive}`)

  mkdirSync(scopeDirectory, { recursive: true })
  const temporaryDirectory = mkdtempSync(join(scopeDirectory, '.oxide-wasm-'))
  const extracted = spawnSync('tar', ['-xzf', archive, '-C', temporaryDirectory], {
    stdio: 'inherit',
  })
  if (extracted.status !== 0) throw new Error('Could not extract the Tailwind WASM binding')

  renameSync(join(temporaryDirectory, 'package'), destination)
  rmdirSync(temporaryDirectory)
}

function collectSourceFiles(directory, files = []) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) collectSourceFiles(path, files)
    else if (supportedExtensions.has(extname(entry.name))) files.push(path)
  }
  return files
}

ensureWindowsWasmBinding()

const { Scanner } = require('@tailwindcss/oxide')
const scanner = new Scanner({ sources: [] })
const sources = collectSourceFiles(join(projectRoot, 'src')).map((path) => ({
  content: readFileSync(path, 'utf8'),
  extension: extname(path).slice(1),
}))
const candidates = scanner.scanFiles(sources).sort()
const inlineSource = JSON.stringify(candidates.join(' '))

writeFileSync(
  generatedPath,
  `/* Generated by scripts/prepare-tailwind.mjs. */\n@source inline(${inlineSource});\n`
)
console.log(`Prepared ${candidates.length} Tailwind candidates.`)
